package com.iostream;

public class MathLibrary {

	public static void main(String[] args)
	{

		System.out.println(Math.abs(67.89));
		System.out.println(Math.sqrt(25.0));
		System.out.println(Math.pow(3, 4));
		System.out.println(Math.PI);
		System.out.println(Math.log(2.0));
		System.out.println(Math.exp(3));
		System.out.println(Math.max(89f, 45f));
		System.out.println(Math.min(67f, 43f));
		System.out.println(Math.ceil(-6.54));
		System.out.println(Math.floor(-78.65));
		


	}

}
